import assert from "node:assert/strict";
import { closeSync, fstatSync, fsyncSync, ftruncateSync, linkSync, mkdirSync, openSync, readFileSync, renameSync, statSync, symlinkSync, writeFileSync, writeSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import { endpointsFileSetting, reloadCommand, runEgress, writeInPlace } from "../src/egress-cli.mjs";
import { renderEndpointsInclude } from "../src/model-endpoints.mjs";
import { main } from "../src/cli.mjs";
import { tempDir } from "./helpers/temp-dir.mjs";

const ONE = { version: 1, endpoints: [{ id: "mac-ollama", host: "host.docker.internal", port: 11434, slots: 2, keyless: true }] };

// The golden for ONE, as the shipped proxy reads it (the render itself is pinned in model-endpoints.test.mjs).
const GOLDEN_ONE = [
	"# Generated by pi-dispatch from model-endpoints.json. Do not edit: regenerate it with `pi-dispatch egress render`.",
	"# Each endpoint is a CONNECT tunnel to exactly one declared host and port, and nothing else (issue #503).",
	"# The host ACL comes first on every line, so squid only ever resolves a declared name.",
	"",
	"# mac-ollama",
	"acl pde_mac-ollama_host dstdomain -n host.docker.internal",
	"acl pde_mac-ollama_port port 11434",
	"acl pde_mac-ollama_local dst 127.0.0.0/8 0.0.0.0/32 10.0.2.2/32 ::1 ::/128",
	"http_access deny CONNECT pde_mac-ollama_host pde_mac-ollama_port pde_mac-ollama_local",
	"http_access allow CONNECT pde_mac-ollama_host pde_mac-ollama_port",
	"",
].join("\n");

/** A deployment folder: the endpoints file, the scaffolded empty include, and an optional .env. */
function deployment({ endpoints = ONE, envText = null, include = renderEndpointsInclude([]) } = {}) {
	const dir = tempDir("pd-egress-cli-");
	if (endpoints !== null) writeFileSync(join(dir, "model-endpoints.json"), JSON.stringify(endpoints));
	if (include !== null) writeFileSync(join(dir, "model-endpoints.conf"), include);
	if (envText !== null) writeFileSync(join(dir, ".env"), envText);
	return dir;
}

async function render(dir, { env = {}, platform = "linux", ...rest } = {}) {
	let out = "";
	let err = "";
	const code = await runEgress(["render"], { env, cwd: dir, platform, out: (s) => (out += s), err: (s) => (err += s), valkeyUrl: () => "redis://127.0.0.1:6379", ...rest });
	return { code, out, err };
}

test("egress render writes the include IN PLACE: same inode, the golden text, and the docker reload printed (#503)", async () => {
	const dir = deployment();
	const path = join(dir, "model-endpoints.conf");
	const before = statSync(path).ino;
	const r = await render(dir);
	assert.equal(r.code, 0, r.err);
	assert.equal(readFileSync(path, "utf8"), GOLDEN_ONE);
	// The measured reason (Docker 29.1.3, Podman 4.9.3 and 5.8.1 on Linux): a single-file bind mount holds the inode,
	// so only a write to the SAME inode is what the running proxy reloads.
	assert.equal(statSync(path).ino, before, "the include keeps its inode");
	assert.match(r.out, /wrote .*model-endpoints\.conf \(in place\)/);
	assert.match(r.out, /^ {2}docker exec pi-dispatch-egress-proxy squid -k reconfigure$/m);
	assert.doesNotMatch(r.out, /\b(docker|podman) restart\b/, "a reconfigure, never a restart");
});

test("egress render: an unchanged include is not written and says so (#503)", async () => {
	const dir = deployment({ include: GOLDEN_ONE });
	let wrote = 0;
	const r = await render(dir, { write: () => wrote++ });
	assert.equal(r.code, 0);
	assert.equal(wrote, 0);
	assert.match(r.out, /already matches the declared model endpoints: nothing written/);
});

test("egress render refuses a symlink, a directory and a missing include, and writes nothing (#503)", async () => {
	const linked = deployment({ include: null });
	writeFileSync(join(linked, "real.conf"), "keep\n");
	symlinkSync(join(linked, "real.conf"), join(linked, "model-endpoints.conf"));
	const a = await render(linked);
	assert.equal(a.code, 1);
	assert.match(a.err, /is a symlink/);
	assert.equal(readFileSync(join(linked, "real.conf"), "utf8"), "keep\n", "nothing written through the link");

	const dird = deployment({ include: null });
	mkdirSync(join(dird, "model-endpoints.conf"));
	const b = await render(dird);
	assert.equal(b.code, 1);
	assert.match(b.err, /is a directory, not a file/);

	const missing = deployment({ include: null });
	const c = await render(missing);
	assert.equal(c.code, 1);
	assert.match(c.err, /does not exist: `pi-dispatch init`/);
	assert.throws(() => statSync(join(missing, "model-endpoints.conf")), /ENOENT/, "a missing include is not created");
});

test("egress render validates before it truncates: a refused declaration leaves the include as it was (#503)", async () => {
	const dir = deployment({ endpoints: { version: 1, endpoints: [{ id: "lo", host: "127.0.0.1", port: 11434, slots: 1 }] }, include: GOLDEN_ONE });
	const r = await render(dir);
	assert.equal(r.code, 1);
	assert.match(r.err, /model-endpoints\.conf was not changed/);
	assert.equal(readFileSync(join(dir, "model-endpoints.conf"), "utf8"), GOLDEN_ONE);
});

test("writeInPlace keeps the inode where a temp file renamed over the path does not (#503)", () => {
	const dir = tempDir("pd-egress-inplace-");
	const path = join(dir, "model-endpoints.conf");
	writeFileSync(path, "old\n");
	const ino = statSync(path).ino;
	writeInPlace(path, "new and longer\n");
	assert.equal(readFileSync(path, "utf8"), "new and longer\n");
	assert.equal(statSync(path).ino, ino);
	writeInPlace(path, "s\n");
	assert.equal(readFileSync(path, "utf8"), "s\n", "truncated, not overlaid");
	// The control: what the render must NOT do.
	writeFileSync(join(dir, "tmp"), "renamed\n");
	renameSync(join(dir, "tmp"), path);
	assert.notEqual(statSync(path).ino, ino);
	assert.throws(() => writeInPlace(join(dir, "absent.conf"), "x"), /ENOENT/, "never creates a file");
});

test("egress render names the reload per venue: podman for the rootless venue, both for both, the operator's own proxy (#503)", async () => {
	const podman = await render(deployment(), { env: { PI_BACKENDS: "podman" } });
	assert.match(podman.out, /^ {2}podman exec pi-dispatch-egress-proxy squid -k reconfigure$/m);
	assert.doesNotMatch(podman.out, /docker exec/);
	const both = await render(deployment(), { env: { PI_BACKENDS: "local,podman" } });
	assert.match(both.out, /docker exec pi-dispatch-egress-proxy squid -k reconfigure/);
	assert.match(both.out, /podman exec pi-dispatch-egress-proxy squid -k reconfigure/);
	const own = await render(deployment(), { env: { PI_EGRESS_PROXY: "my-squid" } });
	assert.match(own.out, /docker exec my-squid squid -k reconfigure/);
	assert.match(own.out, /my-squid is your own proxy/);
	const off = await render(deployment(), { env: { PI_EGRESS: "0" } });
	assert.equal(off.code, 0);
	assert.match(off.out, /egress policy is off/);
	assert.doesNotMatch(off.out, /squid -k reconfigure/);
	assert.equal(reloadCommand("podman", "x"), "podman exec x squid -k reconfigure");
});

test("egress render reads PI_MODEL_ENDPOINTS_FILE from .env, and refuses a shell value that disagrees with it (#503)", async () => {
	const dir = deployment({ endpoints: null, envText: "PI_MODEL_ENDPOINTS_FILE=elsewhere.json\n" });
	writeFileSync(join(dir, "elsewhere.json"), JSON.stringify(ONE));
	const r = await render(dir);
	assert.equal(r.code, 0, r.err);
	assert.equal(readFileSync(join(dir, "model-endpoints.conf"), "utf8"), GOLDEN_ONE);
	assert.deepEqual(endpointsFileSetting({ env: {}, cwd: dir }), { value: "elsewhere.json", note: null });
	const clash = await render(dir, { env: { PI_MODEL_ENDPOINTS_FILE: "other.json" } });
	assert.equal(clash.code, 1);
	assert.match(clash.err, /in this shell and "elsewhere\.json" in .*\.env/);
});

