test("writeInPlace EMPTIES the include when the write fails after the truncate, never leaving it half written (#503 gate A517-2)", () => {
	const dir = tempDir("pd-egress-empty-");
	const path = join(dir, "model-endpoints.conf");
	writeFileSync(path, "old rules\n");
	let writes = 0;
	const failing = { openSync, fstatSync, ftruncateSync, fsyncSync, closeSync, writeSync: (fd, b, off, len) => (writes++ === 0 ? writeSync(fd, b, off, Math.min(len, 20)) : (() => { throw Object.assign(new Error("ENOSPC: no space left on device"), { code: "ENOSPC" }); })()) };
	assert.throws(() => writeInPlace(path, "x".repeat(100), failing), (e) => e.code === "ENOSPC" && e.emptied === true);
	assert.equal(readFileSync(path, "utf8"), "", "empty, which squid reads as no endpoints, not a prefix");
});

test("egress render says EMPTIED when its write failed, and refuses a hard-linked include without touching it (#503 gate A517-2, A517-5)", async () => {
	const dir = deployment();
	const r = await render(dir, { write: () => { throw Object.assign(new Error("EIO"), { code: "EIO", emptied: true }); } });
	assert.equal(r.code, 1);
	assert.match(r.err, /It was EMPTIED rather than left half written, which closes every declared endpoint until a render succeeds/);
	const linked = deployment({ include: "before\n" });
	linkSync(join(linked, "model-endpoints.conf"), join(linked, "other-name.conf"));
	const l = await render(linked);
	assert.equal(l.code, 1);
	assert.match(l.err, /has 2 hard links: a write in place would change every one of them[^\n]*It was not changed/);
	assert.equal(readFileSync(join(linked, "other-name.conf"), "utf8"), "before\n");
});

test("egress render compares PI_MODEL_ENDPOINTS_FILE as paths, and warns when only this shell sets it (#503 gate)", async () => {
	const dir = deployment({ endpoints: null, envText: "PI_MODEL_ENDPOINTS_FILE=elsewhere.json\n" });
	writeFileSync(join(dir, "elsewhere.json"), JSON.stringify(ONE));
	const same = await render(dir, { env: { PI_MODEL_ENDPOINTS_FILE: "./elsewhere.json" } });
	assert.equal(same.code, 0, same.err);
	const shellOnly = deployment({ endpoints: null });
	writeFileSync(join(shellOnly, "mine.json"), JSON.stringify(ONE));
	const r = await render(shellOnly, { env: { PI_MODEL_ENDPOINTS_FILE: "mine.json" } });
	assert.equal(r.code, 0);
	assert.match(r.out, /⚠ PI_MODEL_ENDPOINTS_FILE comes from this shell only, and the service reads .*\.env, which does not set it/);
});

test("egress render's words: off says no reload; unchanged names the reload as an if; a refused declaration with no include says nothing was written (#503 gate)", async () => {
	const off = await render(deployment({ include: GOLDEN_ONE }), { env: { PI_EGRESS: "0" } });
	assert.match(off.out, /nothing written/);
	assert.doesNotMatch(off.out, /reload it as below|reload it/i);
	const same = await render(deployment({ include: GOLDEN_ONE }));
	assert.match(same.out, /If the proxy started before it last changed, reload it \(no restart[^\n]*\n {2}docker exec pi-dispatch-egress-proxy squid -k reconfigure/);
	const bad = { version: 1, endpoints: [{ id: "lo", host: "127.0.0.1", port: 11434, slots: 1 }] };
	const none = await render(deployment({ endpoints: bad, include: null }));
	assert.match(none.err, /Nothing was written\./);
	assert.doesNotMatch(none.err, /was not changed/);
});

test("egress render names the rules refresh when endpoints are declared and the rules the proxy runs predate #503, per venue (#503 gate L517-2)", async () => {
	const PRE = "http_port 3128\n";
	const INCL = "http_port 3128\ninclude /etc/pi-dispatch/model-endpoints.conf\n";
	const docker = deployment();
	mkdirSync(join(docker, "deploy"));
	writeFileSync(join(docker, "deploy", "egress-proxy.conf"), PRE);
	const d = await render(docker);
	assert.match(d.out, /⚠ model endpoints are declared, but deploy\/egress-proxy\.conf predates #503 and does not include model-endpoints\.conf, so the endpoints stay unreachable until the rules are refreshed: `pi-dispatch up`, and accept the refresh/);
	writeFileSync(join(docker, "deploy", "egress-proxy.conf"), INCL);
	assert.doesNotMatch((await render(docker)).out, /predates #503/);
	const home = tempDir("pd-egress-home-");
	mkdirSync(join(home, ".config", "pi-dispatch"), { recursive: true });
	writeFileSync(join(home, ".config", "pi-dispatch", "egress-proxy.conf"), PRE);
	const p = await render(deployment(), { env: { PI_BACKENDS: "podman" }, home });
	assert.match(p.out, /⚠ model endpoints are declared, but the podman proxy's rules \(~\/\.config\/pi-dispatch\/egress-proxy\.conf\) predate #503[^\n]*`pi-dispatch service install --force`/);
	// No endpoints declared: nothing to say.
	const empty = deployment({ endpoints: { version: 1, endpoints: [] } });
	mkdirSync(join(empty, "deploy"));
	writeFileSync(join(empty, "deploy", "egress-proxy.conf"), PRE);
	assert.doesNotMatch((await render(empty)).out, /predates #503/);
});
